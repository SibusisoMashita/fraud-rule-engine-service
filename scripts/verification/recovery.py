"""Actual process/transport/restore drills against the owned Docker project."""
import concurrent.futures
import contextlib
import json
import socket
import subprocess
import time
from datetime import datetime, timezone

from commit_fault import ContainerCommitProxy
from stack import check


def wait_for(predicate, seconds, message):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(.1)
    raise AssertionError(message)


def event(settings, name, customer=None):
    return {**settings['event'], 'eventId': name, 'customerId': customer or name,
            'instrumentId': 'card-' + (customer or name),
            'occurredAt': datetime.now(timezone.utc).isoformat(timespec='microseconds').replace('+00:00', 'Z')}


def post(stack, body, expected=201, service='app'):
    status, response, elapsed = stack.request('/api/v1/transactions', body, service=service)
    check(status == expected, f'POST {body["eventId"]}: {status}, expected {expected}')
    return response, elapsed


def invariant_counts(stack, service='db'):
    query = """
    SELECT json_build_object(
      'transactions', (SELECT count(*) FROM fraud.transactions),
      'evaluations', (SELECT count(*) FROM fraud.evaluations),
      'results', (SELECT count(*) FROM fraud.rule_results),
      'incomplete', (SELECT count(*) FROM fraud.evaluations e WHERE e.expected_rule_count <>
        (SELECT count(*) FROM fraud.rule_results r WHERE r.scope=e.scope AND r.event_id=e.event_id)),
      'navigationMismatch', (SELECT count(*) FROM fraud.evaluations e JOIN fraud.transactions t USING(scope,event_id)
        WHERE (e.customer_id,e.accepted_at) IS DISTINCT FROM (t.customer_id,t.accepted_at)),
      'watermarkMismatch', (SELECT count(*) FROM fraud.evaluations e JOIN fraud.transactions t USING(scope,event_id)
        WHERE e.context_high_watermark<>t.customer_sequence-1),
      'sequenceMismatch', (SELECT count(*) FROM fraud.customer_processing_state c WHERE
        c.customer_sequence<>(SELECT count(*) FROM fraud.transactions t WHERE t.scope=c.scope AND t.customer_id=c.customer_id)
        OR c.customer_sequence<>coalesce((SELECT max(t.customer_sequence) FROM fraud.transactions t
          WHERE t.scope=c.scope AND t.customer_id=c.customer_id),0)),
      'orphan', (SELECT count(*) FROM fraud.transactions t FULL JOIN fraud.evaluations e USING(scope,event_id)
        WHERE t.event_id IS NULL OR e.event_id IS NULL));
    """
    result = json.loads(stack.sql(query, service))
    check(result['transactions'] == result['evaluations'], 'Event/evaluation count mismatch')
    check(all(result[key] == 0 for key in ('incomplete', 'navigationMismatch', 'watermarkMismatch', 'sequenceMismatch', 'orphan')),
          'Financial invariant failed: ' + json.dumps(result))
    return result


def fingerprints(stack, service='db'):
    tables = ('transactions', 'evaluations', 'rule_results', 'customer_processing_state', 'instrument_owners',
              'policy_versions', 'policy_head', 'policy_activations', 'api_principals', 'api_credentials')
    fields = []
    for table in tables:
        fields.append(f"'{table}',(SELECT encode(sha256(convert_to(coalesce(string_agg(to_jsonb(t)::text,E'\\n' "
                      f"ORDER BY to_jsonb(t)::text COLLATE \"C\"),''),'UTF8')),'hex') FROM fraud.{table} t)")
    return json.loads(stack.sql('SELECT json_build_object(' + ','.join(fields) + ')', service))


def count_event(stack, name):
    # Names are generated by this module, never external SQL input.
    return int(stack.sql(f"SELECT count(*) FROM fraud.transactions WHERE scope='ops-0' AND event_id='{name}'"))


@contextlib.contextmanager
def block_evaluations(stack):
    stack.sql("""
      CREATE FUNCTION fraud.ops_block_evaluation() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN PERFORM pg_advisory_xact_lock(918273); RETURN NEW; END $$;
      CREATE TRIGGER ops_block BEFORE INSERT ON fraud.evaluations FOR EACH ROW EXECUTE FUNCTION fraud.ops_block_evaluation();
    """)
    args = ['docker', 'compose', '-p', stack.project, '-f', str(stack.file), 'exec', '-T', 'db',
            'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d', 'fraud', '-At']
    holder = subprocess.Popen(args, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    holder.stdin.write(("SET application_name='fraud-ops-blocker'; BEGIN; SELECT pg_advisory_xact_lock(918273); "
                        f"SELECT pg_sleep({stack.settings['blockerSeconds']}); ROLLBACK;\n").encode())
    holder.stdin.close()
    try:
        wait_for(lambda: stack.sql("SELECT count(*) FROM pg_stat_activity WHERE application_name='fraud-ops-blocker' AND wait_event='PgSleep'") == '1',
                 stack.settings['faultBoundSeconds'], 'Blocker did not acquire advisory lock')
        yield
    finally:
        stack.sql("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE application_name='fraud-ops-blocker'")
        holder.wait(timeout=stack.settings['faultBoundSeconds'])
        stack.sql('DROP TRIGGER ops_block ON fraud.evaluations; DROP FUNCTION fraud.ops_block_evaluation();')


def run(stack, record):
    settings = stack.settings
    stable = event(settings, 'recovery-stable')
    original, _ = post(stack, stable)
    record('baseline', {'invariants': invariant_counts(stack)})

    # Stop shared dependencies and prove protected traffic closes, not just readiness.
    for dependency in ('redis', 'db'):
        stack.compose('stop', dependency)
        began = time.monotonic()
        status, body, elapsed = stack.request('/api/v1/transactions', event(settings, 'outage-' + dependency))
        check(status == 503 and elapsed < settings['faultBoundSeconds'], dependency + ' outage was not bounded/closed')
        check(stack.request('/health/live', authenticated=False)[0] == 200, 'Liveness depended on ' + dependency)
        check(stack.request('/health/ready', authenticated=False)[0] == 503, 'Readiness ignored ' + dependency)
        stack.compose('start', dependency)
        stack.ready()
        check(count_event(stack, 'outage-' + dependency) == 0, 'Outage admitted financial state')
        replay, _ = post(stack, stable, 200)
        check(replay == original, 'Outage changed original response')
        record(dependency + '-outage', {'requestMillis': elapsed * 1000, 'recoveredSeconds': time.monotonic() - began})

    # Block real inserts after event persistence but before evaluation completion.
    with block_evaluations(stack):
        with concurrent.futures.ThreadPoolExecutor(max_workers=settings['burstConcurrency']) as pool:
            began = time.monotonic()
            futures = [pool.submit(stack.request, '/api/v1/transactions', event(settings, f'blocked-{n}'), principal=n % settings['principals'])
                       for n in range(settings['burstConcurrency'])]
            waits = json.loads(stack.sql("SELECT json_build_object('waiting',count(*) FILTER(WHERE wait_event_type='Lock'),'connections',count(*)) FROM pg_stat_activity WHERE usename='fraud_runtime'"))
            results = [future.result() for future in futures]
        check(all(status == 503 and json.loads(body)['outcome'] == 'NOT_ACCEPTED' for status, body, _ in results),
              'Blocked burst did not reject safely')
        check(time.monotonic() - began < settings['faultBoundSeconds'], 'Blocked burst exceeded fault bound')
    wait_for(lambda: stack.sql("SELECT count(*) FROM pg_stat_activity WHERE usename='fraud_runtime' AND state='idle in transaction'") == '0',
             settings['recoveryTimeoutSeconds'], 'Leaked transaction after timeout')
    check(stack.sql("SELECT count(*) FROM fraud.transactions WHERE event_id LIKE 'blocked-%'") == '0', 'Timed out transaction committed')
    check(stack.sql("SELECT count(*) FROM pg_locks l JOIN pg_stat_activity a USING(pid) WHERE a.usename='fraud_runtime' AND l.locktype='advisory'") == '0', 'Fault lock leaked after timeout')
    post(stack, event(settings, 'after-blocked-burst'))
    record('blocked-burst', {**waits, 'requests': len(results), 'maxResponseMillis': max(r[2] for r in results) * 1000,
                             'invariants': invariant_counts(stack)})

    interrupted = event(settings, 'killed-during-write')
    with block_evaluations(stack):
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
            pending = pool.submit(stack.request, '/api/v1/transactions', interrupted)
            wait_for(lambda: int(stack.sql("SELECT count(*) FROM pg_stat_activity WHERE usename='fraud_runtime' AND wait_event_type='Lock' AND query LIKE 'INSERT INTO fraud.evaluations%'")) > 0,
                     settings['faultBoundSeconds'], 'Writer did not reach controlled mid-write barrier')
            check(count_event(stack, interrupted['eventId']) == 0, 'Uncommitted event visible')
            stack.compose('kill', '-s', 'SIGKILL', 'app')
            status, _, _ = pending.result()
            check(status in (0, 503), 'Unexpected interrupted response')
    check(count_event(stack, interrupted['eventId']) == 0, 'Killed partial write survived')
    stack.compose('up', '-d', '--no-build', '--no-deps', 'app')
    stack.ready()
    recovered, _ = post(stack, interrupted)
    again, _ = post(stack, interrupted, 200)
    check(recovered == again, 'Killed write replay differed')
    record('kill-during-write', {'invariants': invariant_counts(stack)})

    # Drop the real PostgreSQL commit reply, not a mocked Java exception.
    proxy = ContainerCommitProxy(stack)
    original_url = stack.config['services']['app']['environment']['DATABASE_URL']
    try:
        stack.config['services']['app']['environment']['DATABASE_URL'] = (
            'jdbc:postgresql://commit-proxy:5432/fraud?currentSchema=fraud&sslmode=disable&gssEncMode=disable')
        stack.save()
        stack.compose('up', '-d', '--no-build', '--no-deps', '--force-recreate', 'app')
        stack.ready()
        ambiguous = event(settings, 'lost-commit-reply')
        proxy.arm()
        status, response, elapsed = stack.request('/api/v1/transactions', ambiguous)
        check(proxy.status()['dropped'], 'Commit fault did not fire')
        check(status == 503 and json.loads(response)['outcome'] == 'UNKNOWN', 'Lost commit reply was not reported UNKNOWN')
        check(count_event(stack, ambiguous['eventId']) == 1, 'Lost acknowledgement did not follow a real commit')
        recovered, _ = post(stack, ambiguous, 200)
        check(json.loads(recovered)['evaluation']['policyHash'] == stack.sql('SELECT policy_hash FROM fraud.policy_head WHERE singleton'), 'Recovered wrong policy')
        record('lost-commit-acknowledgement', {'requestMillis': elapsed * 1000, 'outcome': 'UNKNOWN', 'replayStatus': 200,
                                             'transport': 'compose-network', 'proxyImage': proxy.image,
                                             'invariants': invariant_counts(stack)})
    except BaseException:
        try:
            (stack.output / 'commit-proxy-failure.log').write_text(stack.failure_logs())
        except Exception:
            pass
        raise
    finally:
        stack.config['services']['app']['environment']['DATABASE_URL'] = original_url
        stack.save()
        stack.compose('up', '-d', '--no-build', '--no-deps', '--force-recreate', 'app')
        stack.ready()
        proxy.close()

    # The caller deliberately receives no HTTP response; independently observe the commit.
    unread = event(settings, 'discarded-http-response')
    payload = json.dumps(unread).encode()
    host, port = stack.address().split(':')
    with socket.create_connection((host, int(port)), timeout=settings['requestTimeoutSeconds']) as client:
        headers = (f'POST /api/v1/transactions HTTP/1.1\r\nHost: localhost\r\nX-API-Key: {stack.keys[0]}\r\n'
                   f'Content-Type: application/json\r\nContent-Length: {len(payload)}\r\nConnection: close\r\n\r\n')
        client.sendall(headers.encode() + payload)
        wait_for(lambda: count_event(stack, unread['eventId']) == 1, settings['faultBoundSeconds'], 'Unread response did not commit')
        # Close without reading headers/body: the producer has no success acknowledgement.
    recovered, _ = post(stack, unread, 200)
    check(post(stack, unread, 200)[0] == recovered, 'Lost response replay changed result')
    record('discarded-http-response', {'originalResponseRead': False, 'replayStatus': 200, 'invariants': invariant_counts(stack)})

    # A committed response survives a subsequent abrupt process death.
    stack.compose('kill', '-s', 'SIGKILL', 'app')
    stack.compose('up', '-d', '--no-build', '--no-deps', 'app')
    stack.ready()
    check(post(stack, stable, 200)[0] == original, 'Post-commit kill lost original result')
    record('kill-after-commit', {'invariants': invariant_counts(stack)})

    # Restore onto a separate empty PostgreSQL volume, preserving owners/ACLs.
    before = invariant_counts(stack)
    before_hashes = fingerprints(stack)
    dump = stack.compose('exec', '-T', 'db', 'pg_dump', '-U', 'postgres', '-d', 'fraud', '-Fc')
    began = time.monotonic()
    after_backup = event(settings, 'acknowledged-after-backup')
    post(stack, after_backup)
    stack.compose('up', '-d', '--wait', '--wait-timeout', str(settings['startupTimeoutSeconds']), 'restore-db')
    roles = []
    for role, name in [('fraud_policy_admin', 'db-policy-password'), ('fraud_security_admin', 'db-security-password')]:
        password = (stack.credentials / name).read_text().strip()
        roles.append(f"CREATE ROLE {role} LOGIN PASSWORD '{password}'; GRANT CONNECT ON DATABASE fraud TO {role};")
    stack.sql('\n'.join(roles), 'restore-db')
    stack.compose('exec', '-T', 'restore-db', 'pg_restore', '-U', 'postgres', '-d', 'fraud', '--clean', '--if-exists', '--exit-on-error', data=dump)
    check(invariant_counts(stack, 'restore-db') == before, 'Restored counts differ from backup boundary')
    check(fingerprints(stack, 'restore-db') == before_hashes, 'Restored financial/policy/identity contents differ from backup')
    stack.compose('up', '-d', '--no-build', '--no-deps', 'restore-app')
    stack.ready('restore-app')
    status, restored, _ = stack.request('/api/v1/transactions/' + stable['eventId'], service='restore-app')
    check(status == 200 and restored == original, 'Restore changed committed response')
    check(stack.request('/api/v1/transactions/' + after_backup['eventId'], service='restore-app')[0] == 404, 'Restore hid its RPO boundary')
    replay, _ = post(stack, after_backup, service='restore-app')
    check(post(stack, after_backup, 200, service='restore-app')[0] == replay, 'Restore reconciliation duplicated effect')
    locale_query = "SELECT json_build_object('provider',datlocprovider,'locale',datlocale,'collate',datcollate,'encoding',pg_encoding_to_char(encoding)) FROM pg_database WHERE datname=current_database()"
    restored_locale = json.loads(stack.sql(locale_query, 'restore-db'))
    check(restored_locale['provider'] == 'b' and restored_locale['locale'] == 'C.UTF-8'
          and restored_locale['encoding'] == 'UTF8', 'Restored database has an unexpected locale/encoding')
    record('isolated-restore', {'restoreAndVerificationSeconds': time.monotonic() - began,
                               'sourceLocale': json.loads(stack.sql(locale_query)),
                               'restoredLocale': restored_locale,
                               'backupCounts': before, 'restoredTableHashes': before_hashes, 'acknowledgedMissingAtBoundary': 1,
                               'reconciledMissingEvents': 1, 'invariants': invariant_counts(stack, 'restore-db')})
    stack.compose('stop', 'restore-app', 'restore-db')

    # SIGTERM drains a real in-flight write once its barrier is released.
    draining = event(settings, 'graceful-inflight')
    began = time.monotonic()
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        with block_evaluations(stack):
            pending = pool.submit(stack.request, '/api/v1/transactions', draining)
            wait_for(lambda: int(stack.sql("SELECT count(*) FROM pg_stat_activity WHERE usename='fraud_runtime' AND wait_event_type='Lock' AND query LIKE 'INSERT INTO fraud.evaluations%'")) > 0,
                     settings['faultBoundSeconds'], 'Draining writer did not reach barrier')
            stopping = pool.submit(stack.compose, 'stop', 'app')
            wait_for(lambda: b'Commencing graceful shutdown' in stack.compose('logs', '--tail', '30', 'app'),
                     settings['faultBoundSeconds'], 'SIGTERM did not start graceful drain')
        status, response, _ = pending.result()
        stopping.result()
    check(status == 201, 'Graceful shutdown did not finish admitted write')
    stack.compose('up', '-d', '--no-build', '--no-deps', 'app')
    stack.ready()
    check(post(stack, draining, 200)[0] == response, 'Drained response did not persist')
    record('graceful-inflight', {'stopAndRestartSeconds': time.monotonic() - began, 'invariants': invariant_counts(stack)})

    # Schema mismatch closes readiness. Restore marker, then use real migration entrypoint.
    version = stack.sql('SELECT version FROM fraud.service_metadata')
    stack.sql('UPDATE fraud.service_metadata SET version=999')
    check(stack.request('/health/ready', authenticated=False)[0] == 503, 'Incompatible schema became ready')
    stack.sql('UPDATE fraud.service_metadata SET version=' + version)
    stack.ready()
    stack.compose('run', '--rm', '--no-deps', 'migrate')
    check(post(stack, stable, 200)[0] == original, 'Migration rerun changed original result')
    began = time.monotonic()
    stack.compose('stop', 'app')
    elapsed = time.monotonic() - began
    logs = stack.compose('logs', '--no-color', 'app').decode()
    check('Graceful shutdown complete' in logs, 'No graceful shutdown completion')
    check(elapsed < settings['recoveryTimeoutSeconds'], 'Shutdown exceeded verification bound')
    stack.compose('up', '-d', '--no-build', '--no-deps', 'app')
    stack.ready()
    record('compatibility-migration-shutdown', {'shutdownSeconds': elapsed, 'invariants': invariant_counts(stack)})
